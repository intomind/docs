// An EEG Data notification, read by the published SDK's own decoder.
import * as P from "/assets/vendor/intomind-sdk-1.4.1/protocol.js";

// The IntoMind One's ADC reference and width, as its Device Info
// reports them. A host reads both from the device, never from here.
const VREF_UV = 4_500_000;
const ADC_BITS = 24;
const CHANNELS = 4;

const hex = (bytes) => [...bytes].map((b) => b.toString(16).padStart(2, "0")).join(" ");

// Two samples of four channels at 500 samples per second and gain 24, as a
// device would send them a few seconds into a stream. The values are made
// up to look like EEG; the bytes are the SDK's own encoding of them.
function example(discontinuity) {
  const uv = [[12.4, -8.1, 30.2, 4.9], [11.7, -6.5, 28.8, 6.3]];
  const lsb = (2 * VREF_UV) / (24 * 2 ** ADC_BITS);
  return P.encodePacket({
    index: discontinuity ? 1530 : 1500,
    deviceTime: discontinuity ? 3_060_000n : 3_000_000n,
    gainCode: 6,
    rateCode: 5,
    counts: uv.map((row) => row.map((v) => Math.round(v / lsb))),
    discontinuity,
    samplesLostBefore: discontinuity ? 28 : 0,
  });
}

for (const root of document.querySelectorAll('[data-widget="packet-decoder"]')) {
  root.innerHTML = `
    <h4>Read a sample packet</h4>
    <label for="pk-hex">The bytes of one EEG Data notification, in hexadecimal</label>
    <textarea id="pk-hex" spellcheck="false"></textarea>
    <div class="row" style="margin-top:0.6rem">
      <button type="button" data-example="plain">A packet</button>
      <button type="button" class="quiet" data-example="gap">A packet after lost samples</button>
    </div>
    <div class="result" aria-live="polite"></div>`;
  const input = root.querySelector("textarea");
  const out = root.querySelector(".result");

  const show = () => {
    const text = input.value.replace(/0x/gi, "").replace(/[^0-9a-f]/gi, "");
    if (!text) { out.innerHTML = ""; return; }
    if (text.length % 2) { out.innerHTML = '<p class="bad">An odd number of hex digits is not whole bytes.</p>'; return; }
    const bytes = Uint8Array.from(text.match(/../g).map((h) => parseInt(h, 16)));
    let p;
    try {
      p = P.decodePacket(bytes, CHANNELS);
    } catch (e) {
      out.innerHTML = `<p class="bad">Refused as ${e.reason ?? "invalid"}: ${e.message}.</p>`;
      return;
    }
    const rows = p.counts.map((row, i) => `<tr><td>${p.index + i}</td>${row.map((c) =>
      `<td>${c}<br><small>${P.microvolts(c, VREF_UV, p.gain, ADC_BITS).toFixed(3)} µV</small></td>`).join("")}</tr>`).join("");
    out.innerHTML = `
      <dl class="fields">
        <dt>Kind</dt><dd>${p.synthetic ? "generated by the device (0x04)" : "measured (0x01)"}</dd>
        <dt>Break before it</dt><dd>${p.discontinuity ? `yes, ${p.samplesLostBefore} samples lost` : "no"}</dd>
        <dt>First sample</dt><dd>index ${p.index}, device time ${p.deviceTime} µs</dd>
        <dt>Samples</dt><dd>${p.nSamples} of ${CHANNELS} channels</dd>
        <dt>Rate and gain</dt><dd>${p.sps ?? "unknown"} per second, gain ${p.gain}</dd>
        <dt>Mode</dt><dd>${p.modeName}${p.leadoffActive ? ", lead-off detection on" : ""}${p.usbPresent ? ", on USB power" : ""}</dd>
      </dl>
      <div class="table"><table><thead><tr><th>Index</th>${[...Array(CHANNELS).keys()].map((c) => `<th>Channel ${c + 1}</th>`).join("")}</tr></thead>
      <tbody>${rows}</tbody></table></div>`;
  };

  input.addEventListener("input", show);
  for (const b of root.querySelectorAll("[data-example]")) {
    b.addEventListener("click", () => { input.value = hex(example(b.dataset.example === "gap")); show(); });
  }
  input.value = hex(example(false));
  show();
}
